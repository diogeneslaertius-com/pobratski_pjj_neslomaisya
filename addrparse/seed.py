def fill_provinces(ref) -> None:
    """17 областей + алиасы. Это ручной словарь, он нужен и при работе с OSM-справочником."""
    for canon, ctx, adj in PROVINCES:
        ref.add_province(canon, ctx, adj)


def fill(ref) -> None:
    fill_provinces(ref)
    for name, prov, aliases, republic in CITIES:
        ref.add_city(name, prov, aliases, republic)
    for name, city in DISTRICTS:
        ref.add_district(name, city, "Алматинская область" if city is None else None)
    for city, name, kind, type_, district in ITEMS:
        ref.add_item(city, name, kind, type_, district)
